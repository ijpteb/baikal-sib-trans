/*
 * Настройки сайта (тексты, контакты, мессенджеры, SEO…).
 * Значения по умолчанию заданы в settings_defaults(); в базе хранятся только изменённые через админку.
 */

final class Settings
{
    /** @var array<string, array<string, mixed>>|null */
    private static ?array $stored = null;

    /** @var array<string, int> */
    private static array $updatedAt = [];

    private static function load(): array
    {
        if (self::$stored === null) {
            self::$stored = [];
            foreach (Db::all('SELECT key, value, updated_at FROM settings') as $row) {
                self::$stored[(string) $row['key']] = json_decode_array($row['value']);
                self::$updatedAt[(string) $row['key']] = (int) $row['updated_at'];
            }
        }
        return self::$stored;
    }

    /** Все значения группы (по умолчанию + сохранённые). */
    public static function group(string $group): array
    {
        $defaults = settings_defaults()[$group] ?? [];
        $stored = self::load()[$group] ?? [];
        return array_replace($defaults, $stored);
    }

    /** setting('contacts.email') или setting('contacts') — вся группа. */
    public static function get(string $path, mixed $default = null): mixed
    {
        $parts = explode('.', $path, 2);
        $group = self::group($parts[0]);
        if (!isset($parts[1])) {
            return $group;
        }
        return array_key_exists($parts[1], $group) ? $group[$parts[1]] : $default;
    }

    /** Сохраняет значения группы (остальные ключи группы не трогает). */
    public static function save(string $group, array $values): void
    {
        $merged = array_replace(self::group($group), $values);
        Db::run(
            'INSERT INTO settings (key, value, updated_at) VALUES (?, ?, ?)
             ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at',
            [$group, json_store($merged), time()]
        );
        self::$stored = null;
    }

    /** Когда группа сохранялась в админке последний раз (0 — ни разу). */
    public static function updatedAt(string $group): int
    {
        self::load();
        return self::$updatedAt[$group] ?? 0;
    }

    public static function lastUpdate(): int
    {
        self::load();
        return self::$updatedAt ? max(self::$updatedAt) : 0;
    }
}

function setting(string $path, mixed $default = null): mixed
{
    return Settings::get($path, $default);
}

